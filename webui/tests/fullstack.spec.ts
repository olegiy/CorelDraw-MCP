import { expect, test } from '@playwright/test';

test('real host keeps accepted run after tab closes and rejects anonymous access', async ({ browser }) => {
  const context = await browser.newContext();
  const page = await context.newPage();
  await page.goto('http://127.0.0.1:18880/');
  await page.locator('.context-controls .document-disclosure > summary').click();
  await page.getByRole('button', { name: 'Обновить документы' }).click();
  await expect(page.getByRole('status')).toContainText('completed');
  await page.getByLabel('Целевой документ').selectOption('fixture-b');
  await page.getByLabel('Сообщение агенту').fill('Получить превью');
  await page.getByRole('button', { name: 'Отправить', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('running');
  await page.close();
  const reopened = await context.newPage();
  await reopened.goto('http://127.0.0.1:18880/');
  await expect.poll(async () => {
    const response = await context.request.get('http://127.0.0.1:18880/api/v1/runs');
    const body = await response.json();
    return body.items.find((run: { kind: string }) => run.kind === 'agent')?.status;
  }).toBe('completed');
  const snapshot = await context.request.get('http://127.0.0.1:18880/api/v1/runs');
  const runs = (await snapshot.json()).items;
  expect(runs.filter((run: { kind: string }) => run.kind === 'agent')).toHaveLength(1);
  const anonymous = await browser.newContext();
  const denied = await anonymous.request.get('http://127.0.0.1:18880/api/v1/health');
  expect(denied.status()).toBe(401);
  await anonymous.close();
  await context.close();
});

test('two tabs observe one accepted run and explicit Stop prevents next native step', async ({ browser }) => {
  const context = await browser.newContext();
  const page = await context.newPage();
  await page.goto('http://127.0.0.1:18880/');
  await page.locator('.context-controls .document-disclosure > summary').click();
  await page.getByRole('button', { name: 'Обновить документы' }).click();
  await expect(page.getByRole('status')).toContainText('completed');
  await page.getByLabel('Целевой документ').selectOption('fixture-b');
  await page.getByLabel('Сообщение агенту').fill('Превью, затем закончить');
  await page.getByRole('button', { name: 'Отправить', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('running');
  const second = await context.newPage();
  await second.goto('http://127.0.0.1:18880/');
  await expect(second.getByRole('status')).toContainText('running');
  await second.getByRole('button', { name: 'Стоп', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('stopped');
  await expect(second.getByRole('status')).toContainText('stopped');
  const response = await context.request.get('http://127.0.0.1:18880/api/v1/runs');
  const stopped = (await response.json()).items.find((run: { status: string }) => run.status === 'stopped');
  expect(stopped.stop_requested).toBe(true);
  expect(stopped.counters.calls).toBeLessThanOrEqual(1);
  await context.close();
});

test('minimal profile executes VBA, delivers PNG to model and replaces export without permissions', async ({ browser }) => {
  const context = await browser.newContext(); const page = await context.newPage();
  let forbidden = 0;
  page.on('request', request => { if (/\/confirm$|\/files\/register$|\/recovery\/review$/.test(new URL(request.url()).pathname)) forbidden++; });
  await page.goto('http://127.0.0.1:18880/');
  await page.getByRole('button', { name: 'Настройки модели', exact: true }).click();
  await page.getByLabel('Модель', { exact: true }).fill('fixture');
  await page.getByLabel('API URL', { exact: true }).fill('http://127.0.0.1:1/v1');
  await page.getByLabel('API key', { exact: true }).fill('fixture-key-only-canary');
  const saved = page.waitForRequest(request => request.method() === 'PUT' && /\/profiles\//.test(request.url()));
  await page.getByRole('button', { name: 'Сохранить в Credential Manager', exact: true }).click();
  const profile = (await saved).postDataJSON().profile;
  expect(profile.context_approved).toBeUndefined(); expect(profile.vision).toBeUndefined(); expect(profile.send_preview).toBeUndefined();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.locator('.context-controls .document-disclosure > summary').click();
  await page.getByRole('button', { name: 'Обновить документы', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('completed');
  await page.getByLabel('Целевой документ').selectOption('fixture-b');
  await page.getByLabel('Сообщение агенту').fill('fixture:key-only');
  const accepted = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === '/api/v1/runs');
  await page.getByRole('button', { name: 'Отправить', exact: true }).click();
  const runId = (await (await accepted).json()).id;
  await expect(page.getByRole('status')).toContainText('completed', { timeout: 20000 });
  await expect(page.getByText('Проверенный PNG передан модели; файл заменён.', { exact: true })).toBeVisible();
  const run = await (await context.request.get(`http://127.0.0.1:18880/api/v1/runs/${runId}`)).json();
  expect(run.read_only).toBeUndefined();
  const operations = (await (await context.request.get(`http://127.0.0.1:18880/api/v1/runs/${runId}/operations`)).json()).items;
  const tools = operations.map((item: { prepared: { tool: string } }) => item.prepared.tool);
  expect(tools).toContain('corel_execute_vba'); expect(tools).toContain('corel_inspect_document');
  expect(tools).toContain('corel_preview'); expect(tools).toContain('corel_export');
  const exported = operations.find((item: { prepared: { tool: string } }) => item.prepared.tool === 'corel_export');
  expect(exported.prepared.arguments.overwrite).toBeUndefined(); expect(exported.result.outcome).toBe('succeeded');
  const history = await (await context.request.get(`http://127.0.0.1:18880/api/v1/conversations/${run.conversation_id}/messages`)).text();
  expect(history).toContain('Проверенный PNG передан модели'); expect(history).not.toContain('fixture-key-only-canary');
  expect(history).not.toContain('data:image/png;base64,'); expect(forbidden).toBe(0);
  await context.close();
});

test('actual host preserves cleanup failure and never grants admission through review', async ({ browser }) => {
  const context = await browser.newContext(); const page = await context.newPage();
  await page.goto('http://127.0.0.1:18880/');
  await page.locator('.context-controls .document-disclosure > summary').click();
  await page.getByRole('button', { name: 'Обновить документы' }).click();
  await expect(page.getByRole('status')).toContainText('completed');
  await page.getByLabel('Целевой документ').selectOption('fixture-b');
  await page.getByLabel('Сообщение агенту').fill('fixture:cleanup-failure');
  await page.getByRole('button', { name: 'Отправить', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('halted');
  const runs = await (await context.request.get('http://127.0.0.1:18880/api/v1/runs')).json();
  const halted = runs.items.find((run: { status: string }) => run.status === 'halted');
  await expect(page.getByTestId('global-barrier')).toContainText('CLEANUP_NOT_PROVEN');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Разрешить новый контекст', exact: true })).toHaveCount(0);
  const old = await (await context.request.get(`http://127.0.0.1:18880/api/v1/runs/${halted.id}`)).json();
  expect(old.status).toBe('halted'); expect(old.safety_barrier).not.toBeNull();
  const csrf = (await (await context.request.get('http://127.0.0.1:18880/api/v1/access/session')).json()).csrf_token;
  const headers = { Origin: 'http://127.0.0.1:18880', 'X-Corel-CSRF': csrf };
  const blocked = await context.request.post('http://127.0.0.1:18880/api/v1/actions', { headers, data: { client_request_id: crypto.randomUUID(), conversation_id: crypto.randomUUID(), kind: 'manual', tool: 'corel_create_document', arguments: {} } });
  expect(blocked.status()).toBe(409);
  expect((await context.request.post('http://127.0.0.1:18880/api/v1/recovery/review', { headers, data: { manual_corel_checked: true } })).status()).toBe(404);
  const after = (await (await context.request.get('http://127.0.0.1:18880/api/v1/runs')).json()).items;
  expect(after).toHaveLength(runs.items.length);
  expect((await (await context.request.get('http://127.0.0.1:18880/api/v1/health')).json()).safety_barrier).not.toBeNull();
  await context.close();
});
